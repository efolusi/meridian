#!/usr/bin/env node
// Build the per-component size table: what each deep import of the npm package
// costs once a bundler has minified it.
//
// Each module in dist/<group>/<Name>.js is bundled on its own with rolldown,
// with react, react-dom and recharts left external (an app already pays for
// those) and every Meridian module it imports included. That is the cost of
// `import { X } from '@efolusi/meridian/<group>/<Name>.js'` in an app that uses
// nothing else from Meridian. Two imports that share a dependency (Icon,
// Button, Portal) share those bytes, so the rows do not add up to the total.
//
// Writes site/sizes.json (read by the Docs page) and guidelines/bundle-size.md.
// Builds dist/ first so the numbers always describe the current sources.
//
//   node scripts/build_size_table.mjs
//
// Wired into check_all.mjs as a generator; the stale gate catches a forgotten
// regeneration.
//
// Minified bytes are exact and decide staleness. Gzip bytes come from zlib,
// whose output can differ by a few bytes between CPU architectures, so a gzip
// figure is only rewritten when the minified bytes under it changed. Without
// that, a table generated on an arm64 laptop would read as stale on an x64 CI
// runner.

import { execFileSync } from 'node:child_process';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import zlib from 'node:zlib';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const DIST = path.join(ROOT, 'dist');
export const JSON_OUT = path.join(ROOT, 'site', 'sizes.json');
export const MD_OUT = path.join(ROOT, 'guidelines', 'bundle-size.md');

const gzip = (buf) => zlib.gzipSync(buf, { level: 9 }).length;

/** Every component module in dist/, as group/Name.js, sorted. */
function modules() {
  const out = [];
  for (const group of fs.readdirSync(path.join(ROOT, 'components')).sort()) {
    const dir = path.join(ROOT, 'components', group);
    if (!fs.statSync(dir).isDirectory()) continue;
    for (const f of fs.readdirSync(dir).sort()) {
      if (f.endsWith('.jsx')) out.push(`${group}/${f.replace(/\.jsx$/, '.js')}`);
    }
  }
  return out;
}

async function bundle(rolldown, rel) {
  const build = await rolldown({
    input: path.join(DIST, rel),
    cwd: ROOT,
    // Bare specifiers are the app's own dependencies (react, react-dom, recharts).
    external: (id) => !id.startsWith('.') && !path.isAbsolute(id),
    // Every module starts with 'use client', which rolldown reports and drops.
    logLevel: 'silent',
  });
  const { output } = await build.generate({ format: 'esm', minify: true });
  await build.close();
  return output.filter((o) => o.type === 'chunk').map((o) => o.code).join('');
}

/**
 * Keep the committed gzip figure wherever the minified bytes are unchanged.
 * `previous` and `next` are size records ({ bytes, gzip }) keyed by name.
 */
export function carryGzip(next, previous) {
  const out = {};
  for (const [k, v] of Object.entries(next)) {
    const old = previous?.[k];
    out[k] = old && old.bytes === v.bytes && typeof old.gzip === 'number' ? { ...v, gzip: old.gzip } : v;
  }
  return out;
}

export function kb(bytes) {
  return (bytes / 1024).toFixed(1) + ' kB';
}

/** The markdown page, rendered from the same data as site/sizes.json. */
export function renderMarkdown(data) {
  const lines = [
    '<!-- Generated by scripts/build_size_table.mjs. Do not edit; run npm run check:fix. -->',
    '# Bundle size',
    '',
    'What each component adds to an app that installs `@efolusi/meridian` from npm.',
    '',
    'Every row is one deep import, such as `@efolusi/meridian/forms/Button.js`, bundled on its own and minified. ' +
      'It includes the Meridian modules that component imports and leaves out React, react-dom and recharts, ' +
      'which the app already loads. Components that import the same module (Icon, Button, Portal) share those bytes, ' +
      'so the rows do not add up to the total.',
    '',
    'Any component that renders an icon carries the full icon set, about ' +
      `${kb(data.modules.find((m) => m.module === 'icons/Icon.js')?.gzip ?? 0)} gzipped, ` +
      'because the icon name is a runtime string a bundler cannot tree-shake.',
    '',
    'CSS is not counted per component: `styles.css` ships every component style in one file.',
    '',
    '## Totals',
    '',
    '| File | Size | Gzip |',
    '| --- | ---: | ---: |',
    ...Object.entries(data.totals).map(([k, v]) => `| \`${k}\` | ${kb(v.bytes)} | ${kb(v.gzip)} |`),
    '',
    'The root import, `@efolusi/meridian`, is every component. `_ds_bundle.js` is the zero-build CDN bundle, which also ' +
      'carries each component\'s CSS. The root import is minified; the CSS and the CDN bundle are measured as shipped.',
    '',
    '## Per component',
    '',
    '| Import | Exports | Minified | Gzip |',
    '| --- | --- | ---: | ---: |',
    ...data.modules.map((m) => `| \`${m.module}\` | ${m.exports.join(', ')} | ${kb(m.bytes)} | ${kb(m.gzip)} |`),
    '',
  ];
  return lines.join('\n');
}

function exportsOf(rel) {
  const src = fs.readFileSync(path.join(ROOT, 'components', rel.replace(/\.js$/, '.jsx')), 'utf8');
  return [...src.matchAll(/^export (?:function|const) (\w+)/gm)].map((m) => m[1])
    .filter((n) => n[0] === n[0].toUpperCase());
}

async function main() {
  execFileSync('node', ['scripts/build_npm.mjs'], { cwd: ROOT, stdio: 'pipe' });
  const { rolldown } = await import('rolldown');

  const previous = fs.existsSync(JSON_OUT) ? JSON.parse(fs.readFileSync(JSON_OUT, 'utf8')) : null;
  const prevModules = Object.fromEntries((previous?.modules ?? []).map((m) => [m.module, m]));

  const measured = {};
  for (const rel of modules()) {
    const code = await bundle(rolldown, rel);
    measured[rel] = { bytes: Buffer.byteLength(code), gzip: gzip(code) };
  }
  const kept = carryGzip(measured, prevModules);
  const mods = Object.entries(kept).map(([rel, v]) => ({
    module: rel,
    group: rel.split('/')[0],
    exports: exportsOf(rel),
    bytes: v.bytes,
    gzip: v.gzip,
  }));

  const rootCode = await bundle(rolldown, 'index.js');
  const file = (p) => fs.readFileSync(path.join(ROOT, p));
  const totals = carryGzip({
    '@efolusi/meridian': { bytes: Buffer.byteLength(rootCode), gzip: gzip(rootCode) },
    'dist/components.css': { bytes: file('dist/components.css').length, gzip: gzip(file('dist/components.css')) },
    '_ds_bundle.js': { bytes: file('_ds_bundle.js').length, gzip: gzip(file('_ds_bundle.js')) },
  }, previous?.totals);

  const data = { totals, modules: mods };
  fs.writeFileSync(JSON_OUT, JSON.stringify(data, null, 2) + '\n');
  fs.writeFileSync(MD_OUT, renderMarkdown(data));
  console.log(`size table: ${mods.length} modules -> site/sizes.json, guidelines/bundle-size.md`);
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) await main();
