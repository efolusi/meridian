#!/usr/bin/env python3
"""Generate the root source registry, site/registry.json, and per-item install
files under site/registry/<name>.json with embedded content, from
_ds_manifest.json plus the files on disk. Items follow the public registry
schema so compatible clients can install them from GitHub or the hosted site.

Usage: python3 scripts/build_registry.py
Idempotent; run after adding or renaming components, blocks, or kits.
"""
import json, pathlib, re

ROOT = pathlib.Path(__file__).resolve().parent.parent
WWW = ROOT / "site"
R_DIR = WWW / "registry"

def prompt_summary(prompt_path):
    """First non-heading prose line of a .prompt.md, as the item description."""
    try:
        for line in prompt_path.read_text().splitlines():
            line = line.strip()
            if line and not line.startswith("#"):
                return re.sub(r"\s+", " ", line)[:300]
    except OSError:
        pass
    return ""

def file_entry(path, ftype, embed, target=None):
    rel = str(path.relative_to(ROOT))
    e = {"path": rel, "type": ftype}
    # Generic files and pages have no framework-conventional destination, so
    # the current registry schema requires the registry to state it explicitly.
    if target or ftype in {"registry:file", "registry:page"}:
        e["target"] = target or rel
    if embed:
        e["content"] = path.read_text()
    return e

HOST = "https://meridian.efolusi.com/site/registry"
BASE_ITEM = "meridian-base"

# Registry item names are install contracts. Keep them stable when a source
# gains compositional exports whose declaration order differs from the root.
REGISTRY_NAME_OVERRIDES = {
    "components/ai/Bubble.jsx": "bubble",
    "components/ai/MessageScroller.jsx": "message-scroller",
    "components/dates/Calendar.jsx": "calendar",
    "components/data/Chart.jsx": "chart",
    "components/display/Card.jsx": "card",
    "components/display/Item.jsx": "item",
    "components/display/Direction.jsx": "direction",
    "components/forms/Radio.jsx": "radio-group",
    "components/navigation/Sidebar.jsx": "sidebar",
    "components/feedback/Toast.jsx": "toast",
}

EXTERNAL_DEPENDENCIES = {
    "components/data/Chart.jsx": ["recharts@^3.8.0"],
}

def _source_to_item_name():
    """Map a component sourcePath to the registry item name that ships it."""
    manifest = json.loads((ROOT / "_ds_manifest.json").read_text())
    by_source = {}
    for c in manifest["components"]:
        by_source.setdefault(c["sourcePath"], []).append(c["name"])
    return {
        src: REGISTRY_NAME_OVERRIDES.get(src, names[0].lower())
        for src, names in by_source.items()
    }, by_source


def _registry_deps(jsx, name_of_source):
    """Every other registry item this component's imports require.

    Components import siblings by relative path ('../forms/Button.jsx'), and 85 of
    them pull Button purely for injectEfCss. Those edges have to be declared or a
    CLI writes a file whose imports resolve to nothing.
    """
    deps = set()
    # [^;]* spans lines: `import {\n  Dialog,\n  ...\n} from '../feedback/Dialog.jsx';`
    for spec in re.findall(r"^import\s[^;]*?\sfrom\s+'([^']+)';", jsx.read_text(), re.M):
        if not spec.endswith(".jsx"):
            continue
        target = (jsx.parent / spec).resolve()
        try:
            rel = str(target.relative_to(ROOT))
        except ValueError:
            continue
        dep = name_of_source.get(rel)
        if dep:
            deps.add(dep)
    return sorted(deps)


# Copy-in replacements. A few repository files only work where the zero-build
# site serves them, so the registry ships a generated stand-in at the same target.
REG_SRC = ROOT / "registry"
ICON_SOURCE = "components/icons/Icon.jsx"
FONT_CDN = "https://cdn.jsdelivr.net/npm/@efolusi/meridian-tokens@{version}/assets/fonts/"


def write_copy_in_sources():
    """Regenerate registry/icons/_svg.js and registry/tokens/fonts.css.

    Icon: components/icons/Icon.jsx fetches assets/icons/<name>.svg from a base
    URL only the zero-build site has. Copied into an app it fetches a path the
    app does not serve, and a dev server's SPA fallback answers with index.html.
    registry/icons/Icon.jsx (shared with the npm build) reads every glyph from
    this map instead.

    Fonts: tokens/fonts.css points at ../assets/fonts/*.woff2. Registry files are
    text, so the fonts cannot travel with it, and a bundler fails on (webpack) or
    warns about (Vite) the unresolved url(). The copy points at the same files in
    the published @efolusi/meridian-tokens package, pinned to this release.
    """
    icon_dir = ROOT / "assets" / "icons"
    lines = [
        f"  {json.dumps(f.stem, ensure_ascii=False)}: {json.dumps(f.read_text().strip(), ensure_ascii=False)},"
        for f in sorted(icon_dir.glob("*.svg"), key=lambda f: f.name)
    ]
    (REG_SRC / "icons").mkdir(parents=True, exist_ok=True)
    (REG_SRC / "icons" / "_svg.js").write_text(
        "// Generated by scripts/build_registry.py from assets/icons/. Do not edit.\n"
        "export const SVGS = {\n" + "\n".join(lines) + "\n};\n"
    )
    version = json.loads((ROOT / "_ds_manifest.json").read_text())["version"]
    fonts = (ROOT / "tokens" / "fonts.css").read_text()
    if "url('../assets/fonts/" not in fonts:
        raise SystemExit("tokens/fonts.css no longer uses url('../assets/fonts/...'); update build_registry.py")
    header = (
        "/* Generated by scripts/build_registry.py from tokens/fonts.css. Do not edit.\n"
        "   The fonts load from the published @efolusi/meridian-tokens package. To self-host,\n"
        "   copy its assets/fonts/ into your app and point these url()s at that folder. */\n"
    )
    (REG_SRC / "tokens").mkdir(parents=True, exist_ok=True)
    (REG_SRC / "tokens" / "fonts.css").write_text(
        header + fonts.replace("url('../assets/fonts/", "url('" + FONT_CDN.format(version=version))
    )


CSS_LITERAL = re.compile(r"const CSS = `([\s\S]*?)`;")
CSS_ID = re.compile(r"injectEfCss\('([a-z0-9-]+)', CSS\)")


def css_hash(text):
    """FNV-1a (32-bit) over UTF-16 code units, as injectEfCss computes it in JS."""
    h = 0x811C9DC5
    units = text.encode("utf-16-le")
    for i in range(0, len(units), 2):
        h ^= units[i] | (units[i + 1] << 8)
        h = (h * 0x01000193) & 0xFFFFFFFF
    return f"{h:08x}"


def component_css():
    """Every component's CSS as one static stylesheet, for server-rendered apps.

    Components inject their CSS from render, which does nothing on the server:
    a Next.js or Vite SSR page copied in from the registry arrives unstyled and
    changes when it hydrates. Importing this sheet after styles.css puts the CSS
    in a stylesheet the framework links in the server-rendered HTML.

    The blocks match the npm package's components.css (build_npm.mjs): same
    order, same text, same `meridian` layer, so a copied-in app cascades the
    way an npm app does. `--ef-css-static` lists `<id>_<hash>` for each block.
    injectEfCss skips an id only when the text it was given hashes the same, so
    an edited copy or a component from another release injects its own CSS and
    a stale sheet cannot override it.
    """
    blocks, ids, seen = [], [], {}
    for group in sorted(p for p in (ROOT / "components").iterdir() if p.is_dir()):
        for jsx in sorted(group.glob("*.jsx"), key=lambda f: f.name):
            src = jsx.read_text()
            m = CSS_LITERAL.search(src)
            if not m:
                continue
            rel = str(jsx.relative_to(ROOT))
            if "${" in m.group(1):
                raise SystemExit(f"{rel}: CSS literal contains ${{}}; it cannot be extracted statically")
            # The hash is over the source text; it equals the runtime string only
            # while the literal has no escapes and no carriage returns.
            if "\\" in m.group(1) or "\r" in m.group(1):
                raise SystemExit(f"{rel}: CSS literal contains a backslash or CR; its runtime text would differ from the source")
            found = set(CSS_ID.findall(src))
            if len(found) != 1:
                raise SystemExit(f"{rel}: expected one injectEfCss('<id>', CSS) id, found {sorted(found) or 'none'}")
            css_id = found.pop()
            if css_id in seen:
                raise SystemExit(f"{rel}: injectEfCss id {css_id} is also used by {seen[css_id]}")
            seen[css_id] = rel
            ids.append(f"{css_id}_{css_hash(m.group(1))}")
            blocks.append(f"/* {rel} */{m.group(1).rstrip()}\n")
    return (
        "/* Generated by scripts/build_registry.py from the CSS in components/. Do not edit. */\n"
        "@layer meridian{\n"
        f":root{{--ef-css-static:{' '.join(ids)}}}\n"
        + "".join(blocks) + "}\n"
    )


def write_component_css():
    """Regenerate registry/components.css."""
    (REG_SRC / "components.css").write_text(component_css())


SSR_CSS_ITEM = "meridian-ssr-css"


def ssr_css_item(embed):
    """Opt-in static component CSS for server-rendered apps.

    Kept out of meridian-base on purpose: it changes whenever any component's
    CSS does, and inside base that turned every later `add` in an existing app
    into a conflict on files the user never asked for. Nothing depends on it.
    """
    return [{
        "name": SSR_CSS_ITEM,
        "type": "registry:style",
        "title": "Meridian component CSS for server rendering",
        "description": "Every component's CSS as one static stylesheet. Import it after styles.css in a server-rendered app (Next.js, Remix, Vite SSR) so pages arrive styled instead of changing when they hydrate.",
        "registryDependencies": [f"{HOST}/{BASE_ITEM}.json"],
        "files": [file_entry(REG_SRC / "components.css", "registry:file", embed, target="components.css")],
        "categories": ["foundation"],
    }]


def base_item(embed):
    """The token layer every component styles against.

    Without this, an installed component renders unstyled: it references
    var(--surface-card) and friends that the consuming project has never defined.
    """
    files = [file_entry(ROOT / "styles.css", "registry:file", embed)]
    for css in sorted((ROOT / "tokens").glob("*.css")):
        if css.name == "fonts.css":
            files.append(file_entry(REG_SRC / "tokens" / "fonts.css", "registry:file", embed, target="tokens/fonts.css"))
        else:
            files.append(file_entry(css, "registry:file", embed))
    return [{
        "name": BASE_ITEM,
        "type": "registry:style",
        "title": "Meridian base",
        "description": "Stylesheet entry and the full token layer (colour, typography, spacing, effects) in light, dark and compact. Every other item depends on this.",
        "files": files,
        "categories": ["foundation"],
    }]


def component_items(embed):
    name_of_source, by_source = _source_to_item_name()
    items = []
    for source, names in sorted(by_source.items()):
        jsx = ROOT / source
        base = jsx.with_suffix("")
        dts, prompt = base.with_suffix(".d.ts"), pathlib.Path(str(base) + ".prompt.md")
        group = jsx.parent.name
        if source == ICON_SOURCE:
            files = [
                file_entry(REG_SRC / "icons" / "Icon.jsx", "registry:ui", embed, target=source),
                file_entry(REG_SRC / "icons" / "_svg.js", "registry:file", embed, target="components/icons/_svg.js"),
                file_entry(ROOT / "assets" / "icons" / "LICENSE-Lucide.txt", "registry:file", embed, target="components/icons/LICENSE-Lucide.txt"),
            ]
        else:
            files = [file_entry(jsx, "registry:ui", embed)]
        for extra in (dts, prompt):
            if extra.exists():
                files.append(file_entry(extra, "registry:component", embed))
        deps = _registry_deps(jsx, name_of_source)
        self_name = name_of_source[source]
        reg_deps = [f"{HOST}/{BASE_ITEM}.json"] + [
            f"{HOST}/{d}.json" for d in deps if d != self_name
        ]
        primary = next((name for name in names if name.lower() == self_name), names[0])
        ordered_names = [primary] + [name for name in names if name != primary]
        item = {
            "name": self_name,
            "type": "registry:ui",
            "title": " + ".join(ordered_names),
            "description": prompt_summary(prompt) or f"{names[0]} ({group}) from the Meridian design system.",
            "dependencies": ["react", *EXTERNAL_DEPENDENCIES.get(source, [])],
            "registryDependencies": reg_deps,
            "files": files,
            "categories": [group],
        }
        items.append(item)
    return items

def block_items(embed):
    items = []
    for f in sorted((ROOT / "blocks").glob("*.html")):
        items.append({
            "name": "block-" + f.stem,
            "type": "registry:block",
            "title": f.stem.replace("-", " ").capitalize() + " block",
            "description": f"Pre-composed Meridian section: {f.stem.replace('-', ' ')}.",
            "dependencies": ["react"],
            "registryDependencies": [f"{HOST}/{BASE_ITEM}.json"],
            "files": [file_entry(f, "registry:block", embed)],
            "categories": ["blocks"],
        })
    return items


def template_items(embed):
    """Publish copyable starter journeys from the generated manifest inventory."""
    manifest = json.loads((ROOT / "_ds_manifest.json").read_text())
    items = []
    for template in manifest.get("templates", []):
        folder = template["folder"]
        if not folder.startswith("starters/"):
            continue
        root = ROOT / folder
        files = []
        for path in sorted(root.iterdir()):
            if not path.is_file() or path.name == ".thumbnail":
                continue
            files.append(file_entry(path, "registry:page", embed))
        items.append({
            "name": "starter-" + root.name,
            "type": "registry:page",
            "title": template["name"],
            "description": template["description"],
            "dependencies": ["react", "react-dom"],
            "registryDependencies": [f"{HOST}/{BASE_ITEM}.json"],
            "files": files,
            "categories": ["starters"],
        })
    return items

def main():
    R_DIR.mkdir(exist_ok=True)
    write_copy_in_sources()
    write_component_css()
    index_items, written = [], 0
    for make in (base_item, ssr_css_item, component_items, block_items, template_items):
        for lean, full in zip(make(embed=False), make(embed=True)):
            index_items.append(lean)
            full["$schema"] = "https://ui.shadcn.com/schema/registry-item.json"
            (R_DIR / f"{full['name']}.json").write_text(json.dumps(full, indent=2) + "\n")
            written += 1
    expected = {f"{item['name']}.json" for item in index_items}
    removed = 0
    for stale in R_DIR.glob("*.json"):
        if stale.name not in expected:
            stale.unlink()
            removed += 1
    registry = {
        "$schema": "https://ui.shadcn.com/schema/registry.json",
        "name": "meridian",
        "homepage": "https://github.com/efolusi/meridian",
        "items": index_items,
    }
    payload = json.dumps(registry, indent=2) + "\n"
    # The root catalog makes this public repository directly installable by
    # compatible registry clients. The hosted copy remains the discovery index
    # for the docs site and MCP server.
    (ROOT / "registry.json").write_text(payload)
    (WWW / "registry.json").write_text(payload)
    suffix = f"; removed {removed} stale file(s)" if removed else ""
    print(f"registry.json: {len(index_items)} items; registry/: {written} item files{suffix}")

if __name__ == "__main__":
    main()
